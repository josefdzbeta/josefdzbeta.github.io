"""Write dist/docs/model-validation.md from dist/models/*/validation.json (+ building.json)."""
import json, os, glob, statistics, sys

root = sys.argv[1] if len(sys.argv) > 1 else 'dist'
SRC = {'mykonos': 'https://bamaire.es/mykonos/assets/', 'aura': 'https://bamaire.es/aura/assets/', 'babilonia': 'https://bamaire.es/babilonia/assets/',
       'ciudaddeevora': 'https://bamaire.es/planos/', 'orion': 'https://bamaire.es/orion/assets/', 'argo': 'https://bamaire.es/argo/assets/',
       'lapilara': 'https://bamaire.es/lapilara/assets/', 'perseo': 'https://bamaire.es/perseo/assets/'}
out = ['# Model validation against published plans', '',
       'Generated by `scripts/plans/report.py`. Walls are traced from the raster plan of each PDF. The scale is '
       'calibrated so interior rooms add up to the printed interior areas; then room boundaries that have no wall on '
       'the plan (open plans, corridors split at a doorway, terraces) are moved until each room matches its printed '
       'm². **Raw Δ** is the trace before that fit; **Model Δ** is what the 3D model shows (rooms enclosed by walls '
       'cannot be moved, so their Δ stays). Rooms marked * had no wall between them on the plan. Names marked ° were '
       'not printed on the plan (only the area) and are inferred from the drawing.', '',
       'Measured, not published: storey heights (ground 3,80 m, typical 3,30 m, clear 2,60 m) from the published '
       'orthographic elevation of Mykonos. Inferred: door swing, furniture and sanitary positions (beds follow the bed '
       'symbols of each plan), façade material per panel, orientation (no north arrow on the plans). Mykonos Portal 2 '
       'repeats Portal 1 (client instruction).', '']
for vf in sorted(glob.glob(os.path.join(root, 'models', '*', 'validation.json'))):
    promo = vf.split(os.sep)[-2]; v = json.load(open(vf))
    rows = v['units']; errs = []; unit_err = []
    for code, u in rows.items():
        e = [abs(r['errPct']) for r in u['rooms'] if not r['boundaryInferred']]
        errs += e; unit_err.append((code, statistics.mean([abs(r['errPct']) for r in u['rooms']]) if u['rooms'] else None))
    good = sum(1 for _, e in unit_err if e is not None and e < 10)
    out += [f'## {promo.capitalize()}', '',
            f'- Dwellings traced: **{len(rows)}** · rooms compared: {len(errs)} (walled rooms only)',
            f'- Model room-area Δ (all rooms): median **{statistics.median([abs(r["errPct"]) for u in rows.values() for r in u["rooms"]]):.1f} %**; walled rooms: median {statistics.median(errs):.1f} %, 90th percentile {sorted(errs)[int(len(errs) * .9)]:.1f} %',
            f'- Raw trace mean |Δ| per dwelling (before fitting): median {statistics.median([(u.get("fit") or {}).get("meanAbsErrPct", 0) for u in rows.values()]):.1f} %',
            f'- Dwellings with model mean |Δ| < 10 %: **{good} / {len(rows)}** · room names from {", ".join(sorted(set(u.get("labelsFrom", "pdf-text") for u in rows.values())))}', '']
    bpath = os.path.join(os.path.dirname(vf), 'building.json')
    if os.path.exists(bpath) and json.load(open(bpath))['levels']:
        b = json.load(open(bpath))
        out += ['Building assembly (key plan printed on each PDF):', '']
        for lv, L in b['levels'].items():
            out.append(f'- Level {lv}: ' + (f"{len(L['units'])} dwellings placed ({', '.join(u['code'] + ' · ' + u['placementSource'] for u in L['units'])})" if L['units'] else 'outline only (key-plan contour; dwellings not placed — see gaps)'))
        out.append('')
    out += ['| Dwelling | Source | Útil (plan) | Raw Δ | Beds from plan | Rooms outside ±10 % in the model |', '|---|---|---|---|---|---|']
    for code, u in rows.items():
        bad = ', '.join(f"{r['name']}{'*' if r['boundaryInferred'] else ''}{'°' if r.get('nameInferred') else ''} {r['errPct']:+.0f} %" for r in u['rooms'] if abs(r['errPct']) > 10) or '—'
        src = SRC.get(promo, '') + u['source']
        out.append(f"| {code} | [{u['source']}]({src}) | {u['superficieUtil']} m² | {(u.get('fit') or {}).get('meanAbsErrPct', '—')} % | {u.get('beds', 0)} | {bad} |")
    out.append('')
    rej = v.get('rejected') or {}
    if rej:
        out += ['Not published as 3D (raw trace above 35 % or fitted model above 15 % area-weighted; the visitor is sent to the PDF instead):', '']
        out += [f"- {c}: [{r['source']}]({SRC.get(promo, '') + r['source']}) — mean |Δ| {r['meanAbsErrPct']} %" for c, r in sorted(rej.items())]
        out.append('')
os.makedirs(os.path.join(root, 'docs'), exist_ok=True)
open(os.path.join(root, 'docs', 'model-validation.md'), 'w').write('\n'.join(out))
print('written', len(out), 'lines')
